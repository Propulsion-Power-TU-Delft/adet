"""
Integral boundary-layer model of a blade passage (Aungier, Sec. 9.2), as
used for the throat blockage and the trailing-edge boundary layer.
"""

import numpy as np

from adet.equations.base_equation import EquationBase, EquationConfig
from adet.equations.utils import mass_flow_average, safe_if_else, safe_max
from adet.losses.base_loss import LossModel
from adet.variables import NodeVariables

n0 = NodeVariables(0)
n1 = NodeVariables(1)

SHAPE_FACTOR = 9 / 7


def total_by_momentum(shape: float = SHAPE_FACTOR) -> float:
    """delta / theta of a power-law profile with shape factor ``shape``."""
    return shape * (shape + 1) / (shape - 1)


def energy_by_momentum(shape: float = SHAPE_FACTOR) -> float:
    """delta_E / theta of a power-law profile with shape factor ``shape``."""
    return 4 * shape / (3 * shape - 1)


def blocked_area(width, height, n_blades, thickness):
    """Throat area within ``thickness`` of the blade surfaces and endwalls of
    ``n_blades`` rectangular passages (opposite layers merge once
    ``thickness`` reaches the half-width)."""
    open_width = safe_max(width - 2 * thickness, 0 * width)
    open_height = safe_max(height - 2 * thickness, 0 * height)
    return n_blades * (width * height - open_width * open_height)


class AungierBoundaryLayer(EquationBase):
    """
    Momentum and displacement thickness at the outlet of a passage segment,
    marched from its inlet momentum thickness. The path length is the
    meridional chord over the cosine of the mean flow angle; velocities are
    relative (absolute in a stator). The dissipation coefficient is either
    imposed or computed by ``BoundaryLayerFriction``.
    """

    config = EquationConfig(scaling_factor=(1e-5, 1e-5))

    def residual(
        self,
        rho0: n0.stc.Density.Hint,
        rho1: n1.stc.Density.Hint,
        w0: n0.kin.W_mag.Hint,
        w1: n1.kin.W_mag.Hint,
        beta0: n0.kin.FlowAngleRel.Hint,
        beta1: n1.kin.FlowAngleRel.Hint,
        mer_chord1: n1.geo.MerChord.Hint,
        cd1: n1.oth.BLDissipCoeff.Hint,
        mom_thick0: n0.oth.MomThick.Hint,
        mom_thick1: n1.oth.MomThick.Hint,
        disp_thick1: n1.oth.DispThick.Hint,
    ):
        path_len = mer_chord1 / np.cos((beta0 + beta1) / 2)
        w_mid = (w0 + w1) / 2
        rho_avg = (rho0 + rho1) / 2

        velocity_term = (w0 / w1) ** 5 + (w_mid / w1) ** 5 + 1
        carried = rho0 / rho1 * (w0 / w1) ** 5 * mom_thick0
        generated = cd1 * rho_avg / rho1 * velocity_term * path_len / 8

        r1 = mom_thick1 - (carried + generated)
        r2 = disp_thick1 - SHAPE_FACTOR * mom_thick1
        return r1, r2


class BoundaryLayerFriction(EquationBase):
    """
    Dissipation coefficient of a passage segment as a friction factor:
    laminar Cf = 16 / Re belowRe = 2000, smooth-pipe Colebrook law otherwise,

        1 / sqrt(4 Cf) = -2 log10(2.51 / (Re sqrt(4 Cf)))

    with Re on the segment-averaged density and velocity, the segment
    viscosity (imposed, so that the fluid model needs no transport
    properties), and a characteristic length of either the blade height
    (endwall boundary layers) or the chord (blade boundary layers).
    """

    def __init__(self, characteristic_length: str = 'height', **kwargs):
        super().__init__(**kwargs)
        if characteristic_length not in ('height', 'chord'):
            raise ValueError(f'Unknown characteristic length {characteristic_length}')
        self.characteristic_length = characteristic_length

    def residual(
        self,
        rho0: n0.stc.Density.Hint,
        rho1: n1.stc.Density.Hint,
        w0: n0.kin.W_mag.Hint,
        w1: n1.kin.W_mag.Hint,
        visc1: n1.oth.BLViscosity.Hint,
        hgt0: n0.geo.Height.Hint,
        hgt1: n1.geo.Height.Hint,
        chord1: n1.geo.Chord.Hint,
        cd1: n1.oth.BLDissipCoeff.Hint,
    ):
        if self.characteristic_length == 'height':
            length = (hgt0 + hgt1) / 2
        else:
            length = chord1

        reynolds = (rho0 + rho1) / 2 * (w0 + w1) / 2 * length / visc1

        laminar = cd1 - 16 / reynolds
        turbulent = 1 / (4 * cd1) ** 0.5 + 2 * np.log10(
            2.51 / (reynolds * (4 * cd1) ** 0.5)
        )
        return safe_if_else(reynolds < 2000, laminar, turbulent)


class BoundaryLayerMixedEntropy(LossModel):
    """
    Entropy rise of the passage flow at a rectangular passage section (open
    width = ``ThroatWidth`` - ``BldThick``, see ``BoundaryLayerBlockage``), as the mass
    flow average of the isentropic bulk flow and the boundary layer that
    carries all the entropy generated by dissipation (Denton):
    T Sdot = 1/2 rho V^3 A_E, with A_E the area blocked by the energy
    thickness, over the boundary-layer mass flow rho V (A_delta - A_delta*).
    """

    config = EquationConfig(scaling_factor=(1.0,))

    def residual(
        self,
        s0: n0.stc.Entropy.Hint,
        rho1: n1.stc.Density.Hint,
        w1: n1.kin.W_mag.Hint,
        T1: n1.stc.Temperature.Hint,
        hgt1: n1.geo.Height.Hint,
        w_th1: n1.geo.ThroatWidth.Hint,
        bld_thick1: n1.geo.BldThick.Hint,
        n_bld1: n1.geo.NumBlades.Hint,
        mom_thick1: n1.oth.MomThick.Hint,
        disp_thick1: n1.oth.DispThick.Hint,
        ds_bl1: n1.loss.Ds_boundary_layer.Hint,
    ):
        delta = total_by_momentum() * mom_thick1
        delta_energy = energy_by_momentum() * mom_thick1

        width = w_th1 - bld_thick1
        area_geom = n_bld1 * width * hgt1
        area_bl = blocked_area(width, hgt1, n_bld1, delta)
        area_disp = blocked_area(width, hgt1, n_bld1, disp_thick1)
        area_energy = blocked_area(width, hgt1, n_bld1, delta_energy)

        mf_bulk = rho1 * w1 * (area_geom - area_bl)
        mf_bl = rho1 * w1 * (area_bl - area_disp)
        entropy_flow = 0.5 * rho1 * w1**3 * area_energy / T1

        s_bl = s0 + entropy_flow / mf_bl
        s_mixed = mass_flow_average((s0, s_bl), (mf_bulk, mf_bl))
        return ds_bl1 - (s_mixed - s0)


class DentonEnergyBoundaryLayer(EquationBase):
    """
    Energy thickness at the outlet of a passage segment from Denton's
    energy integral, marched from its inlet momentum thickness:

        rho_1 V_1^3 dE_1 = rho_0 V_0^3 dE_0 + 2 Cd int(rho V^3) dl

    with Cd Denton's dissipation coefficient (T dS/dA = Cd rho V^3) and the
    integral by Simpson's rule on the end states and their mean. Unlike the
    momentum march of ``AungierBoundaryLayer``, all the energy dissipated
    upstream stays in the layer, so the boundary-layer entropy of
    ``BoundaryLayerMixedEntropy`` matches Denton's dissipation integral over
    the passage perimeter. The momentum and displacement thicknesses follow
    from the 1/7-power-law profile (dE = 4H/(3H-1) theta, delta* = H theta).
    The path length is the meridional chord over the cosine of the mean
    flow angle; velocities are relative (absolute in a stator).
    """

    config = EquationConfig(scaling_factor=(1e-5, 1e-5))

    def residual(
        self,
        rho0: n0.stc.Density.Hint,
        rho1: n1.stc.Density.Hint,
        w0: n0.kin.W_mag.Hint,
        w1: n1.kin.W_mag.Hint,
        beta0: n0.kin.FlowAngleRel.Hint,
        beta1: n1.kin.FlowAngleRel.Hint,
        mer_chord1: n1.geo.MerChord.Hint,
        cd1: n1.oth.BLDissipCoeff.Hint,
        mom_thick0: n0.oth.MomThick.Hint,
        mom_thick1: n1.oth.MomThick.Hint,
        disp_thick1: n1.oth.DispThick.Hint,
    ):
        path_len = mer_chord1 / np.cos((beta0 + beta1) / 2)
        rho_mid = (rho0 + rho1) / 2
        w_mid = (w0 + w1) / 2

        # Energy fluxes relative to the outlet one, rho_1 V_1^3
        flux0 = rho0 / rho1 * (w0 / w1) ** 3
        flux_mid = rho_mid / rho1 * (w_mid / w1) ** 3
        carried = flux0 * mom_thick0
        generated = 2 * cd1 * (flux0 + 4 * flux_mid + 1) / 6 * path_len

        r1 = mom_thick1 - (carried + generated / energy_by_momentum())
        r2 = disp_thick1 - SHAPE_FACTOR * mom_thick1
        return r1, r2


class UnguidedSurfaceDissipation(LossModel):
    """
    Entropy rise from Denton's dissipation on the blade surface that extends
    past a passage exit (node 0) into the unguided region up to the trailing
    edge, e.g. the suction side between a nozzle exit line and the trailing
    edge: dS = Cd rho V^3 / T * A / m, with A = Z * b * l the wetted area
    of one side of each blade. The surface length l is the given fraction
    ``surface_fraction`` of the path from node 0 to node 1 (meridional chord
    over the cosine of the passage-exit metal angle); the state is the mean
    of the two nodes.
    """

    config = EquationConfig(scaling_factor=(1.0,))

    def __init__(self, dissipation_coeff: float, surface_fraction: float, **kwargs):
        super().__init__(**kwargs)
        self.cd = dissipation_coeff
        self.surface_fraction = surface_fraction

    def residual(
        self,
        rho0: n0.stc.Density.Hint,
        rho1: n1.stc.Density.Hint,
        w0: n0.kin.W_mag.Hint,
        w1: n1.kin.W_mag.Hint,
        T0: n0.stc.Temperature.Hint,
        T1: n1.stc.Temperature.Hint,
        metal_angle0: n0.geo.MetalAngle.Hint,
        mer_chord1: n1.geo.MerChord.Hint,
        hgt0: n0.geo.Height.Hint,
        n_bld0: n0.geo.NumBlades.Hint,
        mf0: n0.oth.StreamMassFlow.Hint,
        ds_prof1: n1.loss.Ds_profile.Hint,
    ):
        surface_len = self.surface_fraction * mer_chord1 / np.cos(metal_angle0)
        area = n_bld0 * hgt0 * surface_len
        rho, w, temp = (rho0 + rho1) / 2, (w0 + w1) / 2, (T0 + T1) / 2
        return ds_prof1 - self.cd * rho * w**3 / temp * area / mf0
